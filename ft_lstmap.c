#include "libft.h"

t_list	*ft_lstmap(t_list *lst, void *(*f)(void *), void (*del)(void *))
{
	t_list	*new;
	t_list	*node;
	void	*content;

	content = f(lst->content);
	new = NULL;
	if (!f || !del)
		return (NULL);
	node = ft_lstnew(content);
	if (!node)
	{
		del(content);
		ft_lstclear(&new, del);
		return (NULL);
	}
	while (lst)
	{
		node = ft_lstnew(f(lst->content));
		if (!node)
		{
			ft_lstclear(&new, del);
			return (NULL);
		}
		ft_lstadd_back(&new, node);
		lst = lst->next;
	}
	return (new);
}
